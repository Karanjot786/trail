package agents

import (
	"bytes"
	"flag"
	"os"
	"strings"
	"testing"

	"trail/internal/crawlers"
)

var update = flag.Bool("update", false, "rewrite packages/trail-analytics/src/crawl/ua.gen.ts")

const uaGenPath = "../../packages/trail-analytics/src/crawl/ua.gen.ts"

// renderUAGen renders the npm package's UA prefilter from the Go catalogues.
func renderUAGen() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by `go test ./internal/agents -run UAGolden -update`. DO NOT EDIT.\n")
	b.WriteString("// P0 wrote the first copy by hand (AI agents plan §0.8, §0.11); from Task D-1 on the Go golden test owns it.\n\n")
	list := func(doc, name string, items []string) {
		b.WriteString("/** " + doc + " */\n")
		b.WriteString("export const " + name + ": readonly string[] = [\n")
		for _, s := range items {
			b.WriteString("  '" + strings.ReplaceAll(s, "'", "\\'") + "',\n")
		}
		b.WriteString("]\n")
	}
	list("Every AI crawler catalogue name, in catalogue order (internal/crawlers/catalogue.go).", "CRAWLER_TOKENS", crawlers.Names())
	b.WriteString("\n")
	list("User-agent tokens of AI browsing agents (internal/agents catalogue).", "AGENT_TOKENS", uaTokens())
	return b.Bytes()
}

func TestUAGolden(t *testing.T) {
	want := renderUAGen()
	if *update {
		if err := os.WriteFile(uaGenPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(uaGenPath)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale: run go test ./internal/agents -run UAGolden -update\n--- want\n%s", uaGenPath, want)
	}
}
