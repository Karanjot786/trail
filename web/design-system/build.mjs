/* ---------- value -> CSS ---------- */
const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'system-ui', 'ui-sans-serif', 'ui-monospace', 'ui-serif', 'cursive', 'fantasy']);
const family = list => list.map(f => (GENERIC.has(f) || /^[A-Za-z-]+$/.test(f) ? f : `'${f}'`)).join(', ');
const bezier = b => `cubic-bezier(${b.join(', ')})`;
const shadow = list => list.map(s => `${s.inset ? 'inset ' : ''}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`).join(', ');
function css(type, v) {
  switch (type) {
    case 'fontFamily': return family(v);
    case 'cubicBezier': return bezier(v);
    case 'shadow': return shadow(v);
    case 'transition': return `${v.duration} ${bezier(v.timingFunction)}`;
    default: return String(v);
  }
}
const decl = (name, value) => `  --${name}: ${value};`;

/* ---------- non-colour custom properties ---------- */
function staticVars() {
  const out = [];
  const P = tree.primitive, S = tree.semantic;
  for (const [k, t] of Object.entries(P.font.family)) out.push(decl(`font-${k}`, css('fontFamily', t.$value)));
  for (const [k, t] of Object.entries(P.easing)) if (!k.startsWith('$')) out.push(decl(`ease-${k}`, css('cubicBezier', t.$value)));
  out.push('');
  for (const [[, role], t] of walk(S.type, ['type'])) {
    const v = resolve(tree, t.$value);
    const fam = Object.entries(P.font.family).find(([, f]) => JSON.stringify(f.$value) === JSON.stringify(v.fontFamily))[0];
    out.push(decl(`type-${role}`, `${v.fontWeight} ${v.fontSize}/${v.lineHeight} var(--font-${fam})`),
      decl(`text-${role}`, v.fontSize), decl(`leading-${role}`, v.lineHeight), decl(`tracking-${role}`, v.letterSpacing), decl(`weight-${role}`, v.fontWeight));
  }
  out.push('');
  for (const [[, k], t] of walk(P.space, ['space'])) out.push(decl(`space-${k}`, t.$value));
  out.push('');
  for (const [[, k], t] of walk(S.radius, ['radius'])) out.push(decl(`radius-${k}`, resolve(tree, t.$value)));
  out.push('');
  for (const [[, k], t] of walk(S.motion, ['motion'])) {
    const v = resolve(tree, t.$value);
    if (t.$type === 'transition') out.push(decl(`motion-${k}`, css('transition', v)), decl(`duration-${k}`, v.duration));
    else out.push(decl(`duration-${k}`, v));
  }
  out.push('');
  for (const [[, k], t] of walk(S.layout, ['layout'])) out.push(decl(`layout-${k}`, resolve(tree, t.$value)));
  out.push('');
  for (const [[, k], t] of walk(S.z, ['z'])) out.push(decl(`z-${k}`, resolve(tree, t.$value)));
  return out.join('\n');
}

const cssName = k => (k.startsWith('elevation-') ? k : k); // colour roles keep their names: --bg, --fg, --elevation-pop
function themeVars(theme, indent = '  ') {
  return Object.entries(themeTokens(tree, theme)).map(([k, t]) => `${indent}--${cssName(k)}: ${css(t.$type, t.value)};`).join('\n');
}
