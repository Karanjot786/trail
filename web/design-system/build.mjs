/* ---------- preview/index.html (single file: CSS, fonts and data inlined, so it opens from file://) ---------- */
function buildPreview() {
  const { rows } = measure(tree);
  const summary = {};
  for (const th of THEMES) {
    const r = rows.filter(x => x.theme === th);
    const worst = k => { const w = r.filter(x => x.kind === k).sort((a, b) => a.ratio - b.ratio)[0]; return w ? `${w.ratio.toFixed(2)} (${w.pair})` : '-'; };
    summary[th] = { pairs: r.length, worstText: worst('text'), worstGraphic: worst('graphic') };
  }
  const contrastMap = {};
  for (const th of THEMES) for (const [k, t] of walk(tree.theme[th])) if (t.$extensions?.['trail.contrast']) (contrastMap[th] ??= {})[k.join('.')] = t.$extensions['trail.contrast'];
  const primitives = {}, lum = {};
  for (const [ramp, node] of Object.entries(tree.primitive.color)) {
    if (ramp.startsWith('$') || ramp === 'white') continue;
    primitives[ramp] = {};
    for (const [step, t] of Object.entries(node)) if (!step.startsWith('$')) { const v = resolve(tree, t.$value); primitives[ramp][step] = v; lum[v] = luminance(v); }
  }
  const data = {
    version, themes: themesObj, contrast: contrastMap, summary, total: rows.length, primitives, lum, type: typeObj,
    space: flat(tree.primitive.space, num), radius: flat(tree.semantic.radius, num),
    easing: Object.fromEntries(Object.entries(tree.primitive.easing).filter(([k]) => !k.startsWith('$')).map(([k, t]) => [k, t.$value])),
    copyReset: num(resolve(tree, tree.semantic.motion['copy-reset'].$value)),
  };
  const b64 = f => readFileSync(join(ROOT, 'fonts', f)).toString('base64');
  const fonts = fontsCss.replace(banner, '').replace(/url\(\.\/fonts\/([^)]+)\)/g, (_, f) => `url(data:font/woff2;base64,${b64(f)})`);
  const html = readFileSync(join(ROOT, 'preview', 'template.html'), 'utf8')
    .replace('/*@FONTS@*/', () => fonts)
    .replace('/*@TOKENS@*/', () => tokensCss.replace(banner, ''))
    .replace('/*@BASE@*/', () => baseCss.replace(banner, ''))
    .replace('/*@DATA@*/', () => `window.TRAIL = ${JSON.stringify(data)};`);
  writeFileSync(join(ROOT, 'preview', 'index.html'), html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by build.mjs from preview/template.html. Do not edit. -->'));
}
buildPreview();

