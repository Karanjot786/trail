//   dist/tokens.ts      typed constants for JS (charts, canvas, tests)
//   dist/fonts.css      @font-face for Geist, Geist Mono, Doto and the metric-matched fallback
//   dist/base.css       the one focus ring, smoothing, selection, sr-only, tabular numbers
