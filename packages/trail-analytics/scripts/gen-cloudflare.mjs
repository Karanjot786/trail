// Regenerates src/crawl/cloudflare.gen.ts from the server's snapshot (internal/netx/cloudflare-v*.txt).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '../../../internal/netx');
const read = (f) => readFileSync(resolve(dir, f), 'utf8').split(/\s+/).filter(Boolean);
const all = [...read('cloudflare-v4.txt'), ...read('cloudflare-v6.txt')];
const out = `// Generated by scripts/gen-cloudflare.mjs from internal/netx/cloudflare-v{4,6}.txt. Do not edit.
export const CLOUDFLARE_PREFIXES: readonly string[] = ${JSON.stringify(all, null, 2)};
`;
writeFileSync(resolve(here, '../src/crawl/cloudflare.gen.ts'), out);
console.log(`wrote ${all.length} prefixes`);
